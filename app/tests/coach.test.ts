import { coachAnswer, weeklyAverage, CoachContext } from '../src/coach/brain';
import { fmt } from '../src/data/content';
let n = 0;
const ok = (c: boolean, m: string) => { n++; if (!c) throw new Error('FAIL ' + m); console.log('ok', m); };
const base: CoachContext = { goal: 2400, eaten: 1500, burned: 0, p: 80, g: 150, l: 50, earn: 12400, streak: 2, activeDays: 2, pushDone: false, mealsToday: 2, weights: [], startKg: 92, targetKg: 78, tier: { current: 1, toNext: 2.8, remaining: 14, reached: false }, autoGoal: true, hour: 19 };
ok(coachAnswer(base, 'Que manger ce soir ?').includes('900 kcal'), 'ce soir : reste 900 kcal');
ok(coachAnswer({ ...base, eaten: 2600 }, 'je mange quoi ce soir').includes('dépassé de 200'), 'ce soir : dépassé');
ok(coachAnswer(base, 'Pourquoi mon poids stagne ?').includes('pas encore de pesée'), 'poids sans pesée');
const w = Array.from({ length: 14 }, (_, i) => ({ day: '2026-09-' + String(10 + i).padStart(2, '0'), kg: 90 - i * 0.1 }));
const avg = weeklyAverage(w)!;
ok(Math.abs(avg.delta + 0.7) < 0.01, 'moyenne 7 j : −0,7 kg (' + avg.delta + ')');
ok(coachAnswer({ ...base, weights: w }, 'mon poids').includes('baisse de 0,7'), 'poids : tendance baisse');
ok(coachAnswer(base, 'protéines ?').includes('60 g'), 'protéines manquantes 60 g');
ok(coachAnswer(base, 'combien de calories il me reste').includes('900'), 'budget restant');
ok(coachAnswer(base, 'crédits').includes(fmt(12400)), 'crédits réels');
ok(coachAnswer(base, 'défi').includes('5 pompes'), 'défi non fait');
ok(coachAnswer({ ...base, pushDone: true }, 'défi').includes('réussi'), 'défi fait');
ok(coachAnswer(base, 'blabla').includes('900 kcal'), 'fallback avec vraies données');
console.log(n + ' tests coach OK');
