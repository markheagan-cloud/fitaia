import { bmr, dailyGoal, tiers, logWeight, levelFrom, stats, DEFAULT_PROFILE, minGoal } from '../src/store/profile';
let n = 0;
const ok = (c: boolean, m: string) => { n++; if (!c) throw new Error('FAIL ' + m); console.log('ok', m); };
ok(Math.round(bmr('m', 30, 178, 92)) === 1888, 'bmr homme 30 ans 178 cm 92 kg ≈ 1888');
ok(Math.round(bmr('f', 30, 165, 60)) === 1320, 'bmr femme ≈ 1320');
const g = dailyGoal(DEFAULT_PROFILE, 92);
ok(g === 2430, 'objectif perte normal : 1888×1.55−500 ≈ 2430, arrondi 10 → ' + g);
ok(dailyGoal({ ...DEFAULT_PROFILE, sex: 'f', age: 50, heightCm: 155, activity: 'sedentaire', pace: 'rapide', targetKg: 55 }, 60) === 1200, 'plancher 1200 femmes');
ok(dailyGoal({ ...DEFAULT_PROFILE, targetKg: 92 }, 92) === 2930, 'maintien = TDEE');
let t = tiers(DEFAULT_PROFILE, []);
ok(t.current === 1 && t.remaining === 14 && t.toNext === 2.8, 'départ : palier 1, 14 kg restants, 2,8 au suivant');
t = tiers(DEFAULT_PROFILE, [{ day: '2026-10-01', kg: 84.6 }]);
ok(t.current === 3 && t.remaining === 6.6 && t.toNext === 1 && Math.abs(t.toNext - 1) < 0.01, 'à 84,6 kg : palier 3, 6,6 restants, ' + t.toNext + ' au suivant');
t = tiers(DEFAULT_PROFILE, [{ day: '2026-10-01', kg: 78 }]);
ok(t.current === 5 && t.reached, 'objectif atteint : palier 5');
t = tiers(DEFAULT_PROFILE, [{ day: '2026-10-01', kg: 95 }]);
ok(t.current === 1 && t.done === 0, 'prise de poids : reste palier 1');
const w = logWeight(logWeight([], '2026-10-02', 90.26), '2026-10-01', 91);
ok(w.length === 2 && w[0].day === '2026-10-01' && w[1].kg === 90.3, 'journal trié + arrondi 0,1');
ok(logWeight(w, '2026-10-02', 89).length === 2, 'remplace le poids du jour');
ok(levelFrom(0).level === 1 && levelFrom(45).level === 11 && levelFrom(44).level === 10, 'niveaux : 0→1, 45→11');
const st = stats({ '2026-10-01': { challenges: 1, meals: 2, earned: 800 } }, 1, 2, 5, 0);
ok(st.level >= 1 && st.force.level >= 1 && st.force.pct >= 0 && st.force.pct <= 100, 'stats cohérentes ' + JSON.stringify(st));
ok(minGoal('f') === 1200 && minGoal('m') === 1500 && minGoal('x') === 1350, 'plancher de sécurité exposé pour la saisie manuelle');
console.log(n + ' tests profil OK');
